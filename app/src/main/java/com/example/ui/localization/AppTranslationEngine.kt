object AppTranslationEngine {

    /**
     * Translates an Indonesian UI string into Javanese (jv), Sundanese (su), or Malay (ms).
     * Uses longest-match phrase & word replacements so both static and dynamic strings translate naturally.
     */
    fun translateFromIndonesian(lang: AppLanguage, idText: String): String {
        if (idText.isBlank() || lang == AppLanguage.INDONESIAN) return idText
        val dict = when (lang) {
            AppLanguage.JAVANESE -> javaneseTerms
            AppLanguage.SUNDANESE -> sundaneseTerms
            AppLanguage.MALAY -> malayTerms
            else -> return idText
        }
        return applyDictionary(idText, dict)
    }

    /**
     * Translates an English UI string into any of the 17 international languages.
     * Uses longest-match phrase & word replacements so both static and dynamic strings translate naturally.
     */
    fun translateFromEnglish(lang: AppLanguage, enText: String): String {
        if (enText.isBlank() || lang == AppLanguage.ENGLISH) return enText
        val dict = when (lang) {
            AppLanguage.SPANISH -> spanishTerms
            AppLanguage.CHINESE -> chineseTerms
            AppLanguage.CANTONESE -> cantoneseTerms
            AppLanguage.THAI -> thaiTerms
            AppLanguage.TAGALOG -> tagalogTerms
            AppLanguage.FRENCH -> frenchTerms
            AppLanguage.ARABIC -> arabicTerms
            AppLanguage.ITALIAN -> italianTerms
            AppLanguage.JAPANESE -> japaneseTerms
            AppLanguage.KOREAN -> koreanTerms
            AppLanguage.GERMAN -> germanTerms
            AppLanguage.PORTUGUESE -> portugueseTerms
            AppLanguage.RUSSIAN -> russianTerms
            AppLanguage.HINDI -> hindiTerms
            AppLanguage.VIETNAMESE -> vietnameseTerms
            AppLanguage.TURKISH -> turkishTerms
            AppLanguage.DUTCH -> dutchTerms
            else -> return enText
        }
        return applyDictionary(enText, dict)
    }

    /**
     * Translates dynamic Indonesian texts (such as categories, payment methods, default store texts,
     * Bluetooth scan statuses, or ViewModel snackbars) into the target language.
     */
    fun translateDynamicIndonesian(langCode: String, text: String): String {
        val lang = AppLanguage.fromCode(langCode)
        if (lang == AppLanguage.INDONESIAN || text.isBlank()) return text

        // 1. Check exact common dynamic values first (Categories, Payment Methods, Defaults)
        exactDynamicToEnglish[text.trim()]?.let { enEquiv ->
            return if (lang == AppLanguage.ENGLISH) {
                enEquiv
            } else if (lang == AppLanguage.JAVANESE || lang == AppLanguage.SUNDANESE || lang == AppLanguage.MALAY) {
                translateFromIndonesian(lang, text)
            } else {
                translateFromEnglish(lang, enEquiv)
            }
        }

        // 2. For Javanese, Sundanese, Malay: translate directly from Indonesian
        if (lang == AppLanguage.JAVANESE || lang == AppLanguage.SUNDANESE || lang == AppLanguage.MALAY) {
            return translateFromIndonesian(lang, text)
        }

        // 3. Convert Indonesian dynamic text to English first, then to target international language
        val englishText = applyDictionary(text, indonesianToEnglishTerms)
        return if (lang == AppLanguage.ENGLISH) {
            englishText
        } else {
            translateFromEnglish(lang, englishText)
        }
    }

    private fun applyDictionary(input: String, sortedPairs: List<Pair<String, String>>): String {
        var result = input
        for ((src, target) in sortedPairs) {
            if (result.contains(src, ignoreCase = true)) {
                result = replacePreservingCaseOrExact(result, src, target)
            }
        }
        return result
    }

    private fun replacePreservingCaseOrExact(text: String, target: String, replacement: String): String {
        // Use word-boundary aware replacement for short ASCII words to avoid partial word corruption
        val isShortWord = target.length <= 4 && target.all { it.isLetter() }
        return if (isShortWord) {
            val regex = Regex("\\b${Regex.escape(target)}\\b", RegexOption.IGNORE_CASE)
            regex.replace(text, replacement)
        } else {
            val regex = Regex(Regex.escape(target), RegexOption.IGNORE_CASE)
            regex.replace(text, replacement)
        }
    }

    private fun buildSortedTermList(vararg pairs: Pair<String, String>): List<Pair<String, String>> {
        return pairs.sortedByDescending { it.first.length }
    }

