    fun translate(code: String, idText: String, enText: String): String {
        return when (val lang = AppLanguage.fromCode(code)) {
            AppLanguage.INDONESIAN -> idText
            AppLanguage.ENGLISH -> enText
            AppLanguage.JAVANESE,
            AppLanguage.SUNDANESE,
            AppLanguage.MALAY -> AppTranslationEngine.translateFromIndonesian(lang, idText)
            else -> AppTranslationEngine.translateFromEnglish(lang, enText)
        }
    }

    fun translateDynamic(code: String, text: String): String {
        return AppTranslationEngine.translateDynamicIndonesian(code, text)
    }
