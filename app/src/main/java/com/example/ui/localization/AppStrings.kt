package com.example.ui.localization

import androidx.compose.runtime.Composable
import androidx.compose.runtime.ReadOnlyComposable
import androidx.compose.runtime.compositionLocalOf

val LocalAppLanguageCode = compositionLocalOf { "id" }

@Composable
@ReadOnlyComposable
fun tr(idText: String, enText: String): String {
    return AppLocalization.translate(LocalAppLanguageCode.current, idText, enText)
}

@Composable
@ReadOnlyComposable
fun trDynamic(text: String): String {
    return AppLocalization.translateDynamic(LocalAppLanguageCode.current, text)
}

